/** One subtitle line: when it starts, how long it shows, and its text. */
@Serializable
data class Cue(val startMs: Long, val durMs: Long, val text: String) {
    val endMs: Long get() = startMs + durMs
}

/** A video's English subtitles, and Korean ones when the video has them (matched to the English lines). */
@Serializable
data class VideoCaptions(
    val videoId: String,
    val title: String,
    val author: String,
    val lengthSeconds: Int,
    /** True when the English lines are YouTube's automatic captions (lowercase, no punctuation). */
    val autoGenerated: Boolean,
    val cues: List<Cue>,
    /** Same length as [cues]; "" where no Korean line overlaps. Empty when the video has no Korean subtitles. */
    val korean: List<String> = emptyList(),
) {
    /** The line playing at [ms], or -1 before the first line. */
    fun indexAt(ms: Long): Int {
        var lo = 0
        var hi = cues.lastIndex
        var found = -1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            if (cues[mid].startMs <= ms) {
                found = mid
                lo = mid + 1
            } else {
                hi = mid - 1
            }
        }
        return found
    }
}

/** A video the learner opened, for the recent list. */
@Serializable
data class RecentVideo(val videoId: String, val title: String, val author: String)

/** Recognizes YouTube links in whatever was pasted or shared. Pure, so it is unit tested. */
object YouTubeLinks {
    private val patterns = listOf(
        Regex("""(?:youtube\.com|youtube-nocookie\.com)/(?:watch\?(?:[^#\s]*&)?v=|embed/|shorts/|live/|v/)([A-Za-z0-9_-]{11})"""),
        Regex("""youtu\.be/([A-Za-z0-9_-]{11})"""),
    )

    fun videoId(text: String): String? {
        patterns.forEach { p -> p.find(text)?.let { return it.groupValues[1] } }
        val bare = text.trim()
        return bare.takeIf { it.length == 11 && it.all { c -> c.isLetterOrDigit() || c == '_' || c == '-' } }
    }

    fun watchUrl(videoId: String) = "https://youtu.be/$videoId"
}

/** Turns YouTube's timed-text XML into lines. Pure, so it is unit tested. */
object CaptionParser {
    private val textTag = Regex("""<text start="([\d.]+)"(?: dur="([\d.]+)")?[^>]*>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL)
    private val tags = Regex("<[^>]+>")
    private val numeric = Regex("&#(x?)([0-9a-fA-F]+);")

    fun unescape(value: String): String {
        var s = value
        // The text is often escaped twice ("&amp;#39;"), so unescape until nothing changes.
        repeat(2) {
            s = s.replace("&amp;", "&")
                .replace("&lt;", "<").replace("&gt;", ">")
                .replace("&quot;", "\"").replace("&apos;", "'")
            s = numeric.replace(s) { m ->
                val code = m.groupValues[2].toIntOrNull(if (m.groupValues[1].isEmpty()) 10 else 16)
                code?.let { String(Character.toChars(it)) } ?: m.value
            }
        }
        return s
    }

    fun parse(xml: String): List<Cue> = textTag.findAll(xml).mapNotNull { m ->
        val text = unescape(m.groupValues[3]).replace(tags, "").replace('\n', ' ').replace(Regex("\\s+"), " ").trim()
        if (text.isEmpty()) return@mapNotNull null
        val start = (m.groupValues[1].toDouble() * 1000).toLong()
        val dur = m.groupValues[2].toDoubleOrNull()?.let { (it * 1000).toLong() } ?: 2000L
        Cue(start, dur, text)
    }.toList()

    /** For each English line, the Korean line that overlaps it most ("" when none does). */
    fun align(english: List<Cue>, korean: List<Cue>): List<String> {
        if (korean.isEmpty()) return emptyList()
        return english.map { e ->
            korean.maxByOrNull { k -> minOf(e.endMs, k.endMs) - maxOf(e.startMs, k.startMs) }
                ?.takeIf { k -> minOf(e.endMs, k.endMs) - maxOf(e.startMs, k.startMs) > 0 }
                ?.text.orEmpty()
        }
    }

    /** Drops lines that are only sound labels such as "[Music]" or "(Applause)". */
    fun withoutSoundLabels(cues: List<Cue>): List<Cue> =
        cues.filterNot { it.text.matches(Regex("""^[\[(（].*[\])）]$""")) }
}

/**
 * Reads a public YouTube video's subtitles. YouTube has no official way to download another
 * channel's captions, so this asks the same player endpoint the YouTube app uses for the list of
 * caption tracks, then reads the English track (human-made first, automatic otherwise) and a
 * Korean one when it exists. It can stop working if YouTube changes that endpoint.
 * Captions are cached in the app's files, so a video opened once works offline afterwards.
 */
class YouTubeCaptions(private val context: Context) {
    private val json = Json { ignoreUnknownKeys = true }
    private val prefs = context.getSharedPreferences("videos", Context.MODE_PRIVATE)
    private val cacheDir = File(context.filesDir, "videos").apply { mkdirs() }

    class NoCaptions(message: String) : Exception(message)

    suspend fun load(videoId: String): VideoCaptions = withContext(Dispatchers.IO) {
        val cached = File(cacheDir, "$videoId.json")
        if (cached.isFile) {
            runCatching { json.decodeFromString(VideoCaptions.serializer(), cached.readText()) }.getOrNull()?.let {
                remember(it)
                return@withContext it
            }
        }
        val player = CLIENTS.firstNotNullOfOrNull { client -> runCatching { player(videoId, client) }.getOrNull()?.takeIf { it.tracks.isNotEmpty() || it.title.isNotEmpty() } }
            ?: throw NoCaptions("영상 정보를 가져오지 못했어요. 인터넷 연결을 확인해 주세요.")
        val english = player.tracks.filter { it.language.startsWith("en") }
        val track = english.firstOrNull { !it.auto } ?: english.firstOrNull()
            ?: throw NoCaptions("이 영상에는 영어 자막이 없어요. 영어 자막(자동 자막 포함)이 있는 영상을 골라 주세요.")
        val cues = CaptionParser.withoutSoundLabels(CaptionParser.parse(get(track.url, player.userAgent)))
        if (cues.isEmpty()) throw NoCaptions("자막을 읽지 못했어요. 잠시 뒤 다시 시도해 주세요.")
        val koTrack = player.tracks.firstOrNull { it.language == "ko" && !it.auto }
        val korean = koTrack?.let { runCatching { CaptionParser.parse(get(it.url, player.userAgent)) }.getOrNull() }.orEmpty()
        val captions = VideoCaptions(
            videoId = videoId,
            title = player.title,
            author = player.author,
            lengthSeconds = player.lengthSeconds,
            autoGenerated = track.auto,
            cues = cues,
            korean = CaptionParser.align(cues, korean),
        )
        cached.writeText(json.encodeToString(VideoCaptions.serializer(), captions))
        remember(captions)
        captions
    }

    fun recent(): List<RecentVideo> =
        runCatching { json.decodeFromString(ListSerializer(RecentVideo.serializer()), prefs.getString("recent", "[]")!!) }.getOrDefault(emptyList())

    private fun remember(c: VideoCaptions) {
        val list = listOf(RecentVideo(c.videoId, c.title, c.author)) + recent().filter { it.videoId != c.videoId }
        prefs.edit().putString("recent", json.encodeToString(ListSerializer(RecentVideo.serializer()), list.take(30))).apply()
    }

    private data class Track(val language: String, val auto: Boolean, val url: String)
    private data class Player(val title: String, val author: String, val lengthSeconds: Int, val tracks: List<Track>, val userAgent: String)
    private data class Client(val name: String, val version: String, val userAgent: String, val extra: String)

    private fun player(videoId: String, client: Client): Player {
        val body = """{"context":{"client":{"clientName":"${client.name}","clientVersion":"${client.version}","hl":"en"${client.extra}}},"videoId":"$videoId"}"""
        val connection = (URL("https://www.youtube.com/youtubei/v1/player?prettyPrint=false").openConnection() as HttpURLConnection).apply {
            requestMethod = "POST"
            doOutput = true
            connectTimeout = TIMEOUT_MS
            readTimeout = TIMEOUT_MS
            setRequestProperty("Content-Type", "application/json")
            setRequestProperty("User-Agent", client.userAgent)
        }
        connection.outputStream.use { it.write(body.toByteArray()) }
        val text = connection.inputStream.bufferedReader().use { it.readText() }
        val root = json.parseToJsonElement(text).jsonObject
        val details = root["videoDetails"]?.jsonObject
        val tracks = (root["captions"]?.jsonObject?.get("playerCaptionsTracklistRenderer")?.jsonObject?.get("captionTracks") as? JsonArray)
            ?.map { it.jsonObject }
            ?.mapNotNull { t ->
                val url = t.str("baseUrl") ?: return@mapNotNull null
                Track(t.str("languageCode").orEmpty(), t.str("kind") == "asr", url.replace("&fmt=srv3", ""))
            }.orEmpty()
        return Player(
            title = details?.str("title").orEmpty(),
            author = details?.str("author").orEmpty(),
            lengthSeconds = details?.str("lengthSeconds")?.toIntOrNull() ?: 0,
            tracks = tracks,
            userAgent = client.userAgent,
        )
    }

    private fun JsonObject.str(key: String) = this[key]?.let { runCatching { it.jsonPrimitive.content }.getOrNull() }

    private fun get(url: String, userAgent: String): String {
        val connection = (URL(url).openConnection() as HttpURLConnection).apply {
            connectTimeout = TIMEOUT_MS
            readTimeout = TIMEOUT_MS
            setRequestProperty("User-Agent", userAgent)
        }
        return connection.inputStream.bufferedReader().use { it.readText() }
    }

    companion object {
        private const val TIMEOUT_MS = 20_000
        private val CLIENTS = listOf(
            Client("ANDROID", "20.10.38", "com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip", ""","androidSdkVersion":34"""),
            Client("IOS", "20.10.4", "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3 like Mac OS X)", ""","deviceModel":"iPhone16,2""""),
        )
    }
}
